CREATE OR REPLACE FUNCTION public.guard_claim_group(
  p_bot_id bigint,
  p_chat_id text,
  p_title text,
  p_owner_id bigint
) RETURNS jsonb
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  claimed_group jsonb;
BEGIN
  INSERT INTO public.guard_groups AS current_group
    (bot_id, chat_id, title, owner_id)
  VALUES (p_bot_id, p_chat_id, p_title, p_owner_id)
  ON CONFLICT (bot_id, chat_id) DO UPDATE
    SET title = EXCLUDED.title
    WHERE current_group.owner_id = EXCLUDED.owner_id
  RETURNING to_jsonb(current_group) INTO claimed_group;

  IF claimed_group IS NULL THEN
    RAISE EXCEPTION 'Bu guruh allaqachon boshqa bot adminiga biriktirilgan.';
  END IF;
  RETURN claimed_group;
END;
$$;

CREATE OR REPLACE FUNCTION public.guard_increment_warning(
  p_bot_id bigint,
  p_chat_id text,
  p_user_id bigint
) RETURNS integer
LANGUAGE sql
SET search_path = public, pg_temp
AS $$
  INSERT INTO public.guard_warnings (bot_id, chat_id, user_id, count)
  VALUES (p_bot_id, p_chat_id, p_user_id, 1)
  ON CONFLICT (bot_id, chat_id, user_id) DO UPDATE
    SET count = public.guard_warnings.count + 1,
        updated_at = now()
  RETURNING count;
$$;

CREATE OR REPLACE FUNCTION public.guard_decrement_warning(
  p_bot_id bigint,
  p_chat_id text,
  p_user_id bigint
) RETURNS integer
LANGUAGE sql
SET search_path = public, pg_temp
AS $$
  UPDATE public.guard_warnings
  SET count = GREATEST(0, count - 1), updated_at = now()
  WHERE bot_id = p_bot_id AND chat_id = p_chat_id AND user_id = p_user_id
  RETURNING count;
$$;

CREATE OR REPLACE FUNCTION public.guard_event_stats(
  p_bot_id bigint,
  p_chat_id text,
  p_since timestamptz
) RETURNS TABLE (event_type text, event_count bigint)
LANGUAGE sql
STABLE
SET search_path = public, pg_temp
AS $$
  SELECT e.event_type, count(*) AS event_count
  FROM public.guard_events e
  WHERE e.bot_id = p_bot_id
    AND e.chat_id = p_chat_id
    AND e.created_at >= p_since
  GROUP BY e.event_type;
$$;

CREATE OR REPLACE FUNCTION public.guard_record_activity(
  p_bot_id bigint,
  p_chat_id text,
  p_user_id bigint,
  p_activity_date date
) RETURNS void
LANGUAGE sql
SET search_path = public, pg_temp
AS $$
  INSERT INTO public.guard_activity (
    bot_id, chat_id, user_id, activity_date, message_count
  )
  VALUES (p_bot_id, p_chat_id, p_user_id, p_activity_date, 1)
  ON CONFLICT (bot_id, chat_id, user_id, activity_date)
  DO UPDATE SET message_count = public.guard_activity.message_count + 1;
$$;

