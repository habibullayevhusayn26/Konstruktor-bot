CREATE TABLE IF NOT EXISTS public.guard_groups (
  bot_id bigint NOT NULL,
  chat_id text NOT NULL,
  title text NOT NULL,
  owner_id bigint NOT NULL,
  welcome_text text NOT NULL DEFAULT 'Xush kelibsiz, {name}!',
  captcha_enabled boolean NOT NULL DEFAULT true,
  captcha_timeout_seconds integer NOT NULL DEFAULT 60,
  flood_limit integer NOT NULL DEFAULT 5,
  flood_window_seconds integer NOT NULL DEFAULT 10,
  mute_seconds integer NOT NULL DEFAULT 300,
  banned_words jsonb NOT NULL DEFAULT '[]'::jsonb,
  PRIMARY KEY (bot_id, chat_id)
);

CREATE TABLE IF NOT EXISTS public.guard_admins (
  bot_id bigint NOT NULL,
  chat_id text NOT NULL,
  user_id bigint NOT NULL,
  added_by bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (bot_id, chat_id, user_id),
  FOREIGN KEY (bot_id, chat_id)
    REFERENCES public.guard_groups(bot_id, chat_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.guard_warnings (
  bot_id bigint NOT NULL,
  chat_id text NOT NULL,
  user_id bigint NOT NULL,
  count integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (bot_id, chat_id, user_id),
  FOREIGN KEY (bot_id, chat_id)
    REFERENCES public.guard_groups(bot_id, chat_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.guard_captchas (
  bot_id bigint NOT NULL,
  chat_id text NOT NULL,
  user_id bigint NOT NULL,
  expires_at timestamptz NOT NULL,
  PRIMARY KEY (bot_id, chat_id, user_id),
  FOREIGN KEY (bot_id, chat_id)
    REFERENCES public.guard_groups(bot_id, chat_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.guard_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bot_id bigint NOT NULL,
  chat_id text NOT NULL,
  user_id bigint NOT NULL,
  event_type text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (bot_id, chat_id)
    REFERENCES public.guard_groups(bot_id, chat_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.guard_activity (
  bot_id bigint NOT NULL,
  chat_id text NOT NULL,
  user_id bigint NOT NULL,
  activity_date date NOT NULL,
  message_count integer NOT NULL DEFAULT 0,
  PRIMARY KEY (bot_id, chat_id, user_id, activity_date),
  FOREIGN KEY (bot_id, chat_id)
    REFERENCES public.guard_groups(bot_id, chat_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS guard_events_stats
